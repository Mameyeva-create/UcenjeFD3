/* МЕТОД includes() - ПРОВЕРЯЕТ СОДЕРЖИТЬСЯ ЛИ УКАЗАННЫЙ ТЕКСТ ВНУТРИ СТРОКИ */

// Пример: 
let word = 'JavaScript';
console.log(word.includes('Script')); // true


/* ЧТО ВОЗВРАЩАЕТ includes()?
ОН ВСЕГДА ВОЗВРАЩАЕТ ТОЛЬКО ДВА ЗНАЧЕНИЯ:
true — если текст найден;
false — если нет. */ 


