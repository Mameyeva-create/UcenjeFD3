/* УРОК 33. МЕТОД repeat() */

/* МЕТОД repeat() - СЛУЖИТ ДЛЯ ПОВТОРЕНИЯ СТРОКИ НЕСКОЛЬКО РАЗ */

// Пример: 
let text = 'Привет';
console.log(text.repeat(3)); // Привет Привет Привет

// Пример1:
let star = '*';
console.log(star.repeat(20));

/* ВАЖНО -repeat() - НЕ ИЗМЕНЯЕТ ИСХОДНУЮ СТРОКУ, А ВОЗВРАЩАЕТ НОВУЮ */

