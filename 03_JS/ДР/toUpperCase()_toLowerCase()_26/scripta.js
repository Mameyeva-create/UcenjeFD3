/* УРОК 26. МЕТОД toUpperCase() И toLowerCase() */

/* toUpperCase() - ПРЕОБРАЗУЕТ ВСЕ БУКВЫ СТРОКИ В ЗАГЛАВНЫЕ */

// Пример: 
let name = 'Оля';
console.log(name.toUpperCase()); // ОЛЯ

/* toLowerCase() - ПРЕОБРАЗУЕТ ВСЕ БУКВЫ СТРОКИ В СТРОЧНЫЕ */

// Пример:
let city = 'OSIJEK';
console.log(city.toLowerCase()); // osijek

/* ВАЖНО - ЭТИ МЕТОДЫ НЕ ИЗМЕНЯЮТ ИСХОДНУЮ СТРОКУ */

// Применр:
let word = 'JavaScript';
console.log(word.toUpperCase());  // JAVASKRIPT
console.log(word); // JavaScript


